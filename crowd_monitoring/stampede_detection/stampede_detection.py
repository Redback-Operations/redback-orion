def main():
    """Run Stampede Detection from Video Processing JSON metadata."""

    import argparse
    import json

    parser = argparse.ArgumentParser(
        description="Run Stampede Detection from pipeline frame metadata."
    )

    parser.add_argument(
        "--input",
        required=True,
        help="Path to Video Processing JSON metadata.",
    )

    parser.add_argument(
        "--output-root",
        default="stampede_detection/data/output/stampede_runs",
        help="Root directory for stampede detection outputs.",
    )

    parser.add_argument(
        "--camera-id",
        default=None,
        help=(
            "Override camera_id. Not part of the current Video "
            "Processing contract -- required until that contract "
            "adds it."
        ),
    )

    parser.add_argument(
        "--zone-id",
        default=None,
        help=(
            "Override zone_id. Not part of the current Video "
            "Processing contract -- required until that contract "
            "adds it."
        ),
    )

    args = parser.parse_args()

    input_path = Path(args.input).expanduser()

    if not input_path.exists():
        raise FileNotFoundError(
            "Pipeline input JSON not found:\n"
            + str(input_path)
        )

    with input_path.open("r", encoding="utf-8") as file:
        input_data = json.load(file)

    video_id = input_data.get("video_id")

    if not video_id:
        raise ValueError(
            "Pipeline input requires 'video_id'."
        )

    if not input_data.get("frames"):
        raise ValueError(
            "Pipeline input requires a non-empty 'frames' list."
        )

    camera_id, zone_id = resolve_camera_and_zone(
        input_data,
        camera_id_override=args.camera_id,
        zone_id_override=args.zone_id,
    )

    run_dir = (
        Path(args.output_root)
        / str(video_id)
    )

    run_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print()
    print("=" * 70)
    print("STAMPEDE DETECTION PIPELINE RUN")
    print("=" * 70)

    print(f"Video ID  : {video_id}")
    print(f"Camera ID : {camera_id}")
    print(f"Zone ID   : {zone_id}")
    print(f"Frames    : {len(input_data['frames'])}")
    print(f"Output    : {run_dir}")

    features, events = analyse_video(
        input_data=input_data,
        output_dir=run_dir,
        video_id=video_id,
        camera_id=camera_id,
        zone_id=zone_id,
    )

    result = {
        "video_id": video_id,
        "events": events,
    }

    print()
    print("Pipeline result:")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()