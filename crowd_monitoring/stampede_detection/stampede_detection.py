def prepare_pipeline_frames(input_data: dict):
    """Prepare consecutive frame metadata for Stampede Detection.

    The Stampede Detection entry point provides video_id and ordered
    frames containing frame_id, timestamp, and frame_path. The frames
    are generated directly from the input video before this helper
    is called.

    This helper resolves frame paths, derives FPS from timestamps,
    and reads the first valid frame to determine resolution.
    """
    frames = input_data.get("frames", [])

    if not frames:
        raise ValueError(
            "Stampede Detection requires a non-empty 'frames' list."
        )

    prepared_frames = []

    for frame_data in frames:
        frame_id = frame_data.get("frame_id")
        timestamp = frame_data.get("timestamp")
        frame_path = frame_data.get("frame_path")

        if frame_id is None or timestamp is None or not frame_path:
            continue

        resolved_path = Path(frame_path)

        if not resolved_path.is_absolute():
            resolved_path = Path(__file__).resolve().parent.parent / resolved_path

        prepared_frames.append(
            {
                "frame_id": int(frame_id),
                "timestamp": float(timestamp),
                "frame_path": str(resolved_path),
            }
        )

    if not prepared_frames:
        raise ValueError(
            "No valid frames were found in the pipeline input."
        )

    prepared_frames.sort(key=lambda item: item["frame_id"])

    fps = 0.0

    if len(prepared_frames) >= 2:
        time_differences = []

        for previous, current in zip(
            prepared_frames,
            prepared_frames[1:],
        ):
            delta = current["timestamp"] - previous["timestamp"]

            if delta > 0:
                time_differences.append(delta)

        if time_differences:
            median_delta = float(np.median(time_differences))
            fps = 1.0 / median_delta

    if fps <= 0:
        raise ValueError(
            "Could not derive a valid FPS from pipeline frame timestamps."
        )

    width = 0
    height = 0

    for frame_data in prepared_frames:
        frame = cv2.imread(frame_data["frame_path"])

        if frame is not None:
            height, width = frame.shape[:2]
            break

    if width <= 0 or height <= 0:
        raise RuntimeError(
            "Could not read any pipeline frame to determine resolution."
        )

    return prepared_frames, fps, width, height


def analyse_video(
    input_data: dict,
    output_dir: Path,
    video_id: str,
    camera_id: str,
    zone_id: str,
):

    from ultralytics import YOLO

    from huggingface_hub import (
        hf_hub_download
    )

    # ========================================================
    # VIDEO INFORMATION
    # ========================================================

    prepared_frames, fps, width, height = prepare_pipeline_frames(
        input_data
    )

    total_frames = len(prepared_frames)

    duration = (
        prepared_frames[-1]["timestamp"]
        if prepared_frames
        else 0.0
    )

    print()
    print("=" * 70)
    print(
        "VIDEO INFORMATION"
    )
    print("=" * 70)

    print(
        f"Resolution : "
        f"{width} x {height}"
    )

    print(
        f"FPS        : "
        f"{fps:.2f}"
    )

    print(
        f"Frames     : "
        f"{total_frames}"
    )

    print(
        f"Duration   : "
        f"{duration:.2f} seconds"
    )

    # ========================================================
    # YOLO
    # ========================================================

    print()
    print("=" * 70)
    print(
        "LOADING YOLOv8 HEAD MODEL"
    )
    print("=" * 70)

    model_path = hf_hub_download(

        repo_id=(
            "AmineSam/"
            "irail-crowd-counting-yolov8n"
        ),

        filename="best.pt",
    )

    model = YOLO(
        model_path
    )

    print(
        "Model loaded."
    )

    print(
        "Classes:",
        model.names
    )

    # ========================================================
    # TRACKING
    # ========================================================

    print()
    print("=" * 70)
    print(
        "YOLOv8 + BoT-SORT TRACKING"
    )
    print("=" * 70)

    tracking_rows = []

    for frame_data in prepared_frames:

        frame = cv2.imread(
            frame_data["frame_path"]
        )

        if frame is None:
            print(
                f"[WARN] Could not read frame "
                f"{frame_data['frame_id']} — skipping"
            )
            continue

        results = model.track(

            source=frame,

            device=0,

            conf=0.30,

            imgsz=832,

            iou=0.75,

            tracker="botsort.yaml",

            persist=True,

            verbose=False,
        )

        result = results[0]

        if (
            result.boxes is None
            or
            result.boxes.id is None
        ):

            continue

        boxes = (
            result.boxes.xyxy
            .cpu()
            .numpy()
        )

        ids = (
            result.boxes.id
            .cpu()
            .numpy()
            .astype(int)
        )

        confidences = (
            result.boxes.conf
            .cpu()
            .numpy()
        )

        for (
            box,
            track_id,
            confidence,
        ) in zip(
            boxes,
            ids,
            confidences,
        ):

            x1, y1, x2, y2 = box

            cx = (
                x1 +
                x2
            ) / 2.0

            cy = (
                y1 +
                y2
            ) / 2.0

            tracking_rows.append(
                {

                    "frame":
                        frame_data["frame_id"],

                    "track_id":
                        int(
                            track_id
                        ),

                    "x":
                        float(cx),

                    "y":
                        float(cy),

                    "width":
                        float(
                            x2 -
                            x1
                        ),

                    "height":
                        float(
                            y2 -
                            y1
                        ),

                    "confidence":
                        float(
                            confidence
                        ),
                }
            )

    tracking_data = pd.DataFrame(
        tracking_rows
    )

    if tracking_data.empty:

        raise RuntimeError(
            "No tracking detections "
            "were produced."
        )

    print(
        f"Tracking records : "
        f"{len(tracking_data)}"
    )

    print(
        f"Unique track IDs : "
        f"{tracking_data['track_id'].nunique()}"
    )

    print(
        f"Frames tracked   : "
        f"{tracking_data['frame'].nunique()}"
    )

    # ========================================================
    # TRACK FILTERING
    # ========================================================

    config = StampedeConfig()

    lengths = (
        tracking_data
        .groupby("track_id")
        .size()
    )

    valid_ids = lengths[
        lengths
        >= config.min_track_length
    ].index

    tracking_data = (
        tracking_data[
            tracking_data[
                "track_id"
            ].isin(valid_ids)
        ]
        .copy()
    )

    print()
    print("=" * 70)
    print(
        "TRACK FILTERING"
    )
    print("=" * 70)

    print(
        f"Valid tracks    : "
        f"{tracking_data['track_id'].nunique()}"
    )

    # ========================================================
    # MOTION FEATURES
    # ========================================================

    detector = StampedeDetector(
        fps=fps,
        config=config,
    )

    tracking_data = (
        detector.calculate_speed(
            tracking_data
        )
    )

    tracking_data = (
        detector.calculate_acceleration(
            tracking_data
        )
    )

    tracking_data = (
        detector.calculate_direction(
            tracking_data
        )
    )

    tracking_data = (
        detector.calculate_rapid_motion(
            tracking_data
        )
    )

    density = (
        detector.calculate_density(
            tracking_data
        )
    )

    consistency = (
        detector.calculate_direction_consistency(
            tracking_data
        )
    )

    # ========================================================
    # FRAME FEATURES
    # ========================================================

    frame_features = (

        tracking_data

        .groupby("frame")

        .agg(

            head_count=(
                "track_id",
                "nunique",
            ),

            avg_speed=(
                "speed",
                "mean",
            ),

            avg_acceleration=(
                "acceleration_smoothed",
                "mean",
            ),

            rapid_people=(
                "rapid_motion",
                "sum",
            ),
        )

        .reset_index()
    )

    frame_features[
        "rapid_motion_ratio"
    ] = (

        frame_features[
            "rapid_people"
        ]

        /

        frame_features[
            "head_count"
        ].replace(
            0,
            np.nan,
        )
    )

    # IMPORTANT:
    #
    # Density has its own head-count column.
    # We only merge density-change values.
    #
    # This prevents the previous
    # KeyError/head_count collision.

    density_for_merge = density[
        [
            "frame",
            "density_change",
            "density_change_smoothed",
        ]
    ]

    frame_features = (
        frame_features

        .merge(
            density_for_merge,
            on="frame",
            how="left",
        )

        .merge(
            consistency,
            on="frame",
            how="left",
        )
    )

    frame_features = (
        frame_features

        .replace(
            [np.inf, -np.inf],
            np.nan,
        )

        .fillna(0.0)
    )

    # ========================================================
    # OPTICAL FLOW
    # ========================================================

    print()
    print("=" * 70)
    print(
        "STREAMING FARNEBACK OPTICAL FLOW"
    )
    print("=" * 70)

    flow_detector = StampedeDetector(
        fps=fps,
        config=config,
    )

    flow_rows = []

    for frame_data in prepared_frames:

        frame = cv2.imread(
            frame_data["frame_path"]
        )

        if frame is None:
            print(
                f"[WARN] Could not read frame "
                f"{frame_data['frame_id']} — skipping"
            )
            continue

        flow = (
            flow_detector
            .calculate_optical_flow(
                frame
            )
        )

        flow_rows.append(
            {

                "frame":
                    frame_data["frame_id"],

                "optical_flow_magnitude":
                    flow[
                        "optical_flow_magnitude"
                    ],

                "optical_flow_p95":
                    flow[
                        "optical_flow_p95"
                    ],

                "flow_divergence":
                    flow[
                        "flow_divergence"
                    ],

                "motion_entropy":
                    flow[
                        "motion_entropy"
                    ],

                "optical_flow_direction":
                    flow[
                        "optical_flow_direction"
                    ],
            }
        )

    flow_data = pd.DataFrame(
        flow_rows
    )

    print(
        f"Optical-flow frames: "
        f"{len(flow_data)}"
    )

    # ========================================================
    # COMBINE
    # ========================================================

    features = (

        frame_features

        .merge(
            flow_data,
            on="frame",
            how="outer",
        )

        .sort_values(
            "frame"
        )

        .reset_index(
            drop=True
        )
    )

    features[
        "timestamp"
    ] = (

        features[
            "frame"
        ]

        /

        fps
    )

    features = (
        features

        .replace(
            [np.inf, -np.inf],
            np.nan,
        )

        .fillna(0.0)
    )

    # ========================================================
    # NORMAL BASELINE
    # ========================================================

    print()
    print("=" * 70)
    print(
        "NORMAL BEHAVIOUR BASELINE"
    )
    print("=" * 70)

    detector.establish_baseline(
        features
    )

    for (
        name,
        values,
    ) in detector.baseline.items():

        print(
            f"{name:30s} "
            f"mean={values['mean']:.4f} "
            f"std={values['std']:.4f}"
        )

    # ========================================================
    # SUDDEN MOTION
    # ========================================================

    features[
        "sudden_motion_change"
    ] = (

        detector.calculate_sudden_change(
            features
        )
    )

    # ========================================================
    # RISK SCORE
    # ========================================================

    scores = []

    for _, row in features.iterrows():

        scores.append(
            detector.calculate_anomaly_score(
                row
            )
        )

    features[
        "risk_score"
    ] = scores

    # ========================================================
    # RISK SMOOTHING
    # ========================================================

    smoothing_frames = max(

        3,

        int(
            fps
            *
            config.smoothing_window
            /
            2
        ),
    )

    features[
        "risk_score_smoothed"
    ] = (

        features[
            "risk_score"
        ]

        .rolling(
            window=smoothing_frames,
            min_periods=1,
            center=True,
        )

        .median()

        .bfill()

        .ffill()
    )

    # ========================================================
    # THREE STATES
    # ========================================================

    features[
        "state"
    ] = (

        features[
            "risk_score_smoothed"
        ]

        .apply(
            detector.classify_state
        )
    )

    # Compatibility column.
    features[
        "status"
    ] = features[
        "state"
    ]

    # ========================================================
    # PERSISTENT HIGH RISK
    # ========================================================

    persistence_frames = max(

        1,

        int(
            config.persistence_seconds
            * fps
        ),
    )

    high = (

        features[
            "risk_score_smoothed"
        ]

        >=

        config.high_risk_threshold
    )

    group_id = (
        (~high)
        .cumsum()
    )

    consecutive_high = (

        high.astype(int)

        .groupby(
            group_id
        )

        .cumsum()
    )

    features[
        "persistent_high_risk"
    ] = (

        consecutive_high

        >=

        persistence_frames
    )

    # ========================================================
    # ABNORMAL EVENTS (internal grouping)
    # ========================================================

    abnormal = (

        features[
            "state"
        ]

        !=

        "NORMAL"
    )

    gap_frames = max(

        1,

        int(
            config.event_gap_seconds
            * fps
        ),
    )

    event_ids = np.zeros(

        len(features),

        dtype=int,
    )

    event_number = 0

    last_abnormal_index = None

    for (
        i,
        is_abnormal,
    ) in enumerate(
        abnormal.values
    ):

        if is_abnormal:

            if (

                last_abnormal_index
                is None

                or

                i -
                last_abnormal_index
                >
                gap_frames
            ):

                event_number += 1

            event_ids[i] = (
                event_number
            )

            last_abnormal_index = i

    features[
        "event_id"
    ] = event_ids

    # ========================================================
    # REMOVE VERY SHORT EVENTS
    # ========================================================

    minimum_event_frames = max(

        1,

        int(
            config.minimum_abnormal_duration
            * fps
        ),
    )

    for event_id in sorted(
        set(event_ids)
    ):

        if event_id == 0:

            continue

        count = int(

            (
                features[
                    "event_id"
                ]

                ==

                event_id
            )

            .sum()
        )

        if (
            count
            <
            minimum_event_frames
        ):

            features.loc[

                features[
                    "event_id"
                ]

                ==

                event_id,

                "event_id",
            ] = 0

    # ========================================================
    # RE-NUMBER EVENTS
    # ========================================================

    mapping = {}

    current = 0

    for event_id in sorted(
        set(
            features[
                "event_id"
            ]
        )
    ):

        if event_id == 0:

            continue

        current += 1

        mapping[
            event_id
        ] = current

    features[
        "event_id"
    ] = (

        features[
            "event_id"
        ]

        .map(
            lambda x:
            mapping.get(
                x,
                0,
            )
        )
    )

    # ========================================================
    # BUILD EVENT SUMMARIES
    # ========================================================

    events = build_event_summaries(

        features,

        video_id,

        camera_id,

        zone_id,
    )

    # Build a complete per-frame output for every frame, including NORMAL frames.
    detections = build_stampede_detections(

        features,

        camera_id,

        zone_id,
    )

    # ========================================================
    # FINAL JSON OUTPUTS
    # ========================================================

    confirmed_events = [
        event
        for event in events
        if event["stampede_detected"]
    ]

    events_path = (
        output_dir /
        "stampede_events.json"
    )

    confirmed_events_json = {

        "video_id":
            video_id,

        "events":
            confirmed_events,
    }

    with open(
        events_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            confirmed_events_json,
            file,
            indent=4,
        )

    output_path = (
        output_dir /
        "stampede_output.json"
    )

    complete_output = {

        "video_id":
            video_id,

        "camera_id":
            camera_id,

        "zone_id":
            zone_id,

        "frame_source":
            "video_input",

        "detector_version":
            "V3.4",

        # Complete per-frame analysis output, including NORMAL frames.
        "total_detections":
            len(detections),

        "detections":
            detections,

        # Grouped abnormal-event summaries (WARNING + CRITICAL).
        "events":
            events,
    }

    with open(
        output_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            complete_output,
            file,
            indent=4,
        )

    # ========================================================
    # OUTPUT INFORMATION
    # ========================================================

    print()
    print("=" * 70)
    print("FINAL OUTPUTS")
    print("=" * 70)

    print(
        f"Stampede events : {events_path}"
    )

    print(
        f"Full output     : {output_path}"
    )

    print()
    print(
        "STAMPEDE DETECTION COMPLETE"
    )

    print("=" * 70)

    return features, events


